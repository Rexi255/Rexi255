GLYPHS = {ch: [row for row in rows.split()] for ch, rows in _GLYPHS.items()}
assert all(len(g) == ROWS and all(len(r) == COLS for r in g) for g in GLYPHS.values())


def width(text):
    """Breite des Textes in Punkt-Spalten (inkl. Lücken zwischen Zeichen)."""
    return len(text) * COLS + (len(text) - 1) * GAP if text else 0


def cells(text):
    """Alle Rasterpunkte des Textes: (spalte, zeile, an?), zeilenweise von oben.

    Lücken-Spalten zwischen den Zeichen sind enthalten (immer aus), damit
    ein Display ein durchgehendes Punktraster zeigt.
    """
    out = []
    for i, ch in enumerate(text):
        glyph = GLYPHS.get(ch)
        if glyph is None:
            raise KeyError(f"Dot-Matrix: Zeichen {ch!r} nicht definiert")
        x0 = i * (COLS + GAP)
        for row in range(ROWS):
            for col in range(COLS):
                out.append((x0 + col, row, glyph[row][col] == "#"))
            if i < len(text) - 1:
                out.append((x0 + COLS, row, False))
    return out
